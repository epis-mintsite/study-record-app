// ── route handler ─────────────────────────────────────────────────────────────

export async function POST(req: NextRequest) {
  void req;
  try {
    // 1. 管理者チェック
    const supabase = await createServerSupabaseClient();
    const { data: { user } } = await supabase.auth.getUser();
    if (!user) {
      return NextResponse.json({ error: '認証が必要です。' }, { status: 401 });
    }
    const supabaseAdmin = createAdminClient();
    const { data: callerRow } = await supabaseAdmin
      .from('users')
      .select('role')
      .eq('id', user.id)
      .single();
    if (callerRow?.role !== 'admin') {
      return NextResponse.json({ error: '管理者権限が必要です。' }, { status: 403 });
    }

    // 2. 既存 Supabase ユーザーを全取得（メール照合用）
    const { data: { users: allSupabaseUsers } } = await supabaseAdmin.auth.admin.listUsers({ perPage: 1000 });

    const results: { userId: string; action: string; recordsInserted: number }[] = [];

    for (const demo of DEMO_USERS) {
      const email = `${demo.userId}@example.com`;
      let supabaseUid: string;

      // 2a. Supabase に既存ユーザーがあるか確認
      const existingSupabase = allSupabaseUsers?.find(u => u.email === email) ?? null;

      if (existingSupabase) {
        supabaseUid = existingSupabase.id;

        // users テーブルの name/role を上書き
        await supabaseAdmin
          .from('users')
          .update({ role: demo.role, name: demo.name })
          .eq('id', supabaseUid);

        results.push({ userId: demo.userId, action: 'existing_user', recordsInserted: 0 });
      } else {
        // 2b. Firebase ユーザー作成（既存ならスキップ）
        let firebaseUid: string | null = null;
        try {
          const fbUser = await getAdminAuth().createUser({ email, password: demo.password });
          firebaseUid = fbUser.uid;
        } catch (err: unknown) {
          const fbErr = err as { code?: string };
          if (fbErr?.code === 'auth/email-already-exists') {
            const existing = await getAdminAuth().getUserByEmail(email);
            firebaseUid = existing.uid;
          } else {
            throw err;
          }
        }

        // 2c. Supabase Auth ユーザー作成
        const tempPw = crypto.randomUUID() + crypto.randomUUID();
        const { data: newUser, error: createError } = await supabaseAdmin.auth.admin.createUser({
          email,
          password: tempPw,
          email_confirm: true,
        });
        if (createError || !newUser.user) {
          if (firebaseUid) await getAdminAuth().deleteUser(firebaseUid).catch(() => {});
          return NextResponse.json({ error: `Supabaseユーザー作成失敗: ${demo.userId}` }, { status: 500 });
        }
        supabaseUid = newUser.user.id;

        // 2d. users テーブル更新
        await supabaseAdmin
          .from('users')
          .update({ role: demo.role, name: demo.name })
          .eq('id', supabaseUid);

        results.push({ userId: demo.userId, action: 'created', recordsInserted: 0 });
      }

      // 3. study_records を upsert（8月分 31日）
      const dayData = SEED_DATA[demo.userId] ?? {};
      let inserted = 0;

      for (const [date, slots] of Object.entries(dayData)) {
        if (!slots || slots.length === 0) continue; // 記録なし日はスキップ
        const dailyTotals = computeDailyTotals(slots);
        const { error } = await supabaseAdmin
          .from('study_records')
          .upsert(
            { user_id: supabaseUid, date, time_slots: slots, daily_totals: dailyTotals },
            { onConflict: 'user_id,date' }
          );
        if (!error) inserted++;
      }

      // 4. weekly_reviews を upsert
      const reviews = REVIEW_DATA[demo.userId] ?? [];
      for (const rev of reviews) {
        await supabaseAdmin
          .from('weekly_reviews')
          .upsert(
            {
              user_id: supabaseUid,
              week_start: rev.weekStart,
              study_snapshot: rev.studySnapshot,
              review_text: rev.reviewText,
              improvement: rev.improvement,
              test_strategy: rev.testStrategy,
              updated_at: new Date().toISOString(),
            },
            { onConflict: 'user_id,week_start' }
          );
      }

      const last = results[results.length - 1];
      last.recordsInserted = inserted;
    }

    return NextResponse.json({ ok: true, results });
  } catch (err) {
    console.error('seed-demo-data error:', err);
    return NextResponse.json({ error: 'シードデータの挿入に失敗しました。' }, { status: 500 });
  }
}
